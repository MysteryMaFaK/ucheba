def set_text(p, text):
    """Меняет текст абзаца, сохраняя форматирование первого прогона."""
    runs = p.runs
    if not runs:
        p.add_run(text)
        return p
    runs[0].text = text
    runs[0].font.highlight_color = None  # шаблон местами размечен жёлтым
    for r in runs[1:]:
        r._element.getparent().remove(r._element)
    return p


def set_image(p, fname):
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    # красная строка шаблона выталкивала бы картинку в правое поле
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.left_indent = Cm(0)
    pf.right_indent = Cm(0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(os.path.join(SHOTS, fname), width=IMG_W)
    return p


def clone_after(p, anchor):
    """Копия абзаца p, вставленная после anchor."""
    new_el = copy.deepcopy(p._p)
    anchor._p.addnext(new_el)
    return Paragraph(new_el, p._parent)


