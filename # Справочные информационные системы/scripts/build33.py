def set_text(p, text):
    for h in p._p.findall(qn('w:hyperlink')):
        p._p.remove(h)
    runs = p.runs
    if not runs:
        p.add_run(text); return p
    runs[0].text = text
    runs[0].font.highlight_color = None
    for r in runs[1:]:
        r._element.getparent().remove(r._element)
    return p


def add(donor, text=''):
    el = copy.deepcopy(donor)
    sectPr.addprevious(el)
    p = set_text(Paragraph(el, doc), text)
    if donor is D_TXT:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent = Cm(1.25)
    elif donor is D_CAP:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
    return p


def quote(text):
    """Цитата из документа — с отступом и без красной строки."""
    p = add(D_TXT, text)
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.left_indent = Cm(1.25)
    for r in p.runs:
        r.italic = True
    return p


def figure(folder, fname, caption):
    el = copy.deepcopy(D_IMG)
    sectPr.addprevious(el)
    p = Paragraph(el, doc)
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0); pf.left_indent = Cm(0); pf.right_indent = Cm(0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(os.path.join(folder, fname), width=IMG_W)
    add(D_CAP, caption)


